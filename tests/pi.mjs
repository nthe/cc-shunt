import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync, symlinkSync, realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checkRead, loadConfig, runTask } from "../adapters/pi/runtime.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const work = mkdtempSync(join(tmpdir(), "shunt-pi-test-"));
const saved = { ...process.env };
let checks = 0;
try {
  mkdirSync(join(work, ".pi"));
  mkdirSync(join(work, "nested"));
  writeFileSync(join(work, ".pi/shunt.json"), JSON.stringify({ root, model: "test/worker", hooks: true }));
  const config = loadConfig(join(work, "nested"));
  assert.equal(config.model, "test/worker");
  assert.equal(config.root, root);
  writeFileSync(join(work, "small.txt"), "test reference\n");
  writeFileSync(join(work, "large.txt"), "line\n".repeat(351));
  assert.match(checkRead(config, work, "read", { path: "large.txt" }), /shunt_scout/);
  assert.equal(checkRead(config, work, "read", { path: "large.txt", limit: 10 }), undefined);
  assert.match(checkRead(config, work, "bash", { command: "cat 'large.txt'" }), /shunt_scout/);
  assert.equal(checkRead({ ...config, hooks: false }, work, "read", { path: "large.txt" }), undefined);
  checks++;
  writeFileSync(join(work, "pi"), `#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
let input = '';
for await (const chunk of process.stdin) input += chunk;
writeFileSync(process.env.SHUNT_PI_TEST_CAPTURE, JSON.stringify({args:process.argv.slice(2), input, active:process.env.SHUNT_ACTIVE, cwd:process.cwd()}));
if (process.env.SHUNT_PI_TEST_MODE === 'hang') setInterval(() => {}, 1000);
else if (process.env.SHUNT_PI_TEST_MODE === 'fail') process.exit(1);
else {
  console.log(JSON.stringify({type:'tool_execution_start',toolName:'read',args:{path:'small.txt'}}));
  console.log(JSON.stringify({type:'message_update',assistantMessageEvent:{type:'text_delta',delta:'a'}}));
  const line = JSON.stringify({type:'message_end',message:{role:'assistant',stopReason:'stop',content:[{type:'text',text:'const answer = "café";'}],usage:{input:20,output:10,cost:{total:0.001}}}});
  for (const byte of Buffer.from(line)) { process.stdout.write(Buffer.from([byte])); await new Promise(resolve => setImmediate(resolve)); }
}
`, { mode: 0o755 });
  process.env.PATH = `${work}:${saved.PATH}`;
  process.env.SHUNT_PI_TEST_CAPTURE = join(work, "capture.json");
  const updates = [];
  const result = await runTask(config, work, "bulk-reader", { question: "Find the value", paths: ["small.txt"] }, undefined, (details) => updates.push(details));
  assert.equal(result.content[0].text, 'const answer = "café";');
  assert.equal(result.details.input, 20);
  assert.equal(result.details.output, 10);
  assert.equal(result.details.cost, 0.001);
  assert.ok(updates.some((update) => update.status === "read: small.txt"));
  const capture = JSON.parse(readFileSync(process.env.SHUNT_PI_TEST_CAPTURE, "utf8"));
  assert.equal(capture.active, "1");
  assert.ok(capture.args.includes("--no-extensions"));
  assert.ok(capture.args.includes("--no-mcp"));
  assert.ok(capture.args.includes("read,grep,find,ls"));
  assert.equal(capture.args[capture.args.indexOf("--model") + 1], "test/worker");
  assert.equal(JSON.parse(capture.input).files[0], join(work, "small.txt"));
  checks++;
  const scout = await runTask(config, join(work, "nested"), "scout", { task: "Trace the value", paths: [".."] });
  assert.equal(scout.details.agent, "scout");
  const scoutCapture = JSON.parse(readFileSync(process.env.SHUNT_PI_TEST_CAPTURE, "utf8"));
  assert.equal(JSON.parse(scoutCapture.input).task, "Trace the value");
  assert.equal(JSON.parse(scoutCapture.input).paths[0], realpathSync(work));
  assert.equal(JSON.parse(scoutCapture.input).project, realpathSync(work));
  assert.equal(realpathSync(scoutCapture.cwd), realpathSync(work));
  await assert.rejects(runTask(config, work, "scout", { task: "Trace", paths: [".."] }), /inside the project/);
  await assert.rejects(runTask(config, work, "scout", { task: " ", paths: ["nested"] }), /task/);
  checks++;
  const target = join(work, "generated.js");
  const writer = await runTask(config, work, "code-writer", { spec: "Write code", reference: ["small.txt"], target }, undefined);
  assert.match(readFileSync(target, "utf8"), /café/);
  assert.equal(writer.content[0].text, `Wrote ${target}.`);
  assert.ok(!writer.content[0].text.includes("const answer"));
  rmSync(process.env.SHUNT_PI_TEST_CAPTURE);
  await assert.rejects(runTask(config, work, "code-writer", { spec: "Write code", reference: ["small.txt"], target }, undefined), /Target exists/);
  assert.ok(!existsSync(process.env.SHUNT_PI_TEST_CAPTURE));
  symlinkSync(target, join(work, "linked.js"));
  await assert.rejects(runTask(config, work, "code-writer", { spec: "Write code", reference: ["small.txt"], target: "linked.js", overwrite: true }, undefined), /symbolic link/);
  checks++;
  writeFileSync(join(work, "binary.bin"), Buffer.from([0, 1]));
  await assert.rejects(runTask(config, work, "bulk-reader", { question: "Read", paths: ["binary.bin"] }, undefined), /Binary/);
  writeFileSync(join(work, "bad.txt"), Buffer.from([255]));
  await assert.rejects(runTask(config, work, "bulk-reader", { question: "Read", paths: ["bad.txt"] }, undefined));
  assert.ok(!existsSync(process.env.SHUNT_PI_TEST_CAPTURE));
  checks++;
  process.env.SHUNT_ACTIVE = "1";
  assert.equal(checkRead(config, work, "read", { path: "large.txt" }), undefined);
  await assert.rejects(runTask(config, work, "bulk-reader", { question: "Read", paths: ["small.txt"] }, undefined), /Nested/);
  delete process.env.SHUNT_ACTIVE;
  checks++;
  process.env.SHUNT_PI_TEST_MODE = "fail";
  await assert.rejects(runTask(config, work, "code-writer", { spec: "Write", reference: ["small.txt"], target, overwrite: true }, undefined), /worker failed/);
  assert.match(readFileSync(target, "utf8"), /café/);
  checks++;
  process.env.SHUNT_PI_TEST_MODE = "hang";
  const controller = new AbortController();
  const task = runTask(config, work, "bulk-reader", { question: "Read", paths: ["small.txt"] }, controller.signal);
  setTimeout(() => controller.abort(), 100);
  await assert.rejects(task, /canceled/);
  process.env.SHUNT_TIMEOUT_SECONDS = "1";
  await assert.rejects(runTask(config, work, "bulk-reader", { question: "Read", paths: ["small.txt"] }, undefined), /timed out/);
  checks++;
  console.log(`Pi: ${checks} checks passed`);
} finally {
  process.env = saved;
  rmSync(work, { recursive: true, force: true });
}
